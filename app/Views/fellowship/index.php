				<h3>2026-2027 Fellowship Recipients</h3>
				
				<p>
				<strong>Dr. Karis Shearer, Associate Professor at the University of British Columbia.</strong>
				</p>
				<p>
				Dr. Shearer's project, <i>“Daphne Marlatt: A Biography,”</i> examines the life and cultural work of the acclaimed Canadian poet, 
				novelist, and editor Daphne Marlatt. During her research residency, Shearer will be working with the <a href="https://bpsc.library.ualberta.ca/collections/black-sparrow-press-archive" target=_blank>Black Sparrow Archive</a> held 
				in Bruce Peel Special Collections, which holds the manuscript (original typescript), page proofs, galley proofs, and 1st edition copy 
				of Daphne Marlatt's first book of poetry, entitled leaf leaf/s and a set of letters from Marlatt to her publisher, John Martin. By 
				situating these items alongside material in the University of Alberta Archive, Shearer aims to recover the author-publisher relationships and archival history that brought 
				Marlatt’s early experimental work into the world. A historical recovery project and the first formal biography of Daphne Marlatt, this project will contribute to the fields of sound studies, feminist theory, and archival studies.
				</p>

				<p>
				<strong>Casarina Hocevar, PhD Candidate at Carleton University.
				</strong>
				</p>
				<p>
				Casarina Hocevar's project, “The Shaping of Canadian Culinary Communities in Edmonton and Beyond, 1930-1980,” examines the intersections among gardening, foodways, and identity within settler communities in the mid-20th-century Edmonton area.  During her research residency, she will draw extensively on three distinct collections held at Bruce Peel Special Collections: the
				<a href="https://bpsc.library.ualberta.ca/collections/linda-miron-distad-culinaria" target="_blank">Linda Miron Distad Culinaria</a> collection, the <a href="https://bpsc.library.ualberta.ca/collections/chinese-experience-in-canada" target="_blank">Chinese Experience in Canada</a> Collection, 
				and <a href="https://bpsc.library.ualberta.ca/collections/prairie-ephemera" target="_blank">Prairie Ephemera</a>, which hold items such as cookbooks, photographs, restaurant menus, and business cards to explore the roles of community grocers and official settlement perspectives. Hocevar plans to connect these archival materials with oral histories that highlight how settlers adapted their culinary cultures in Canada rather than being strictly shaped by state expectations.
				</p>
				
