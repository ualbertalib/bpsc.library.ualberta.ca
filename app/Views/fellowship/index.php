				<h3>Terms of the fellowship</h3>

					<p>Each fellow is expected to spend a minimum of two weeks conducting on-site research, and all research must be completed between June 1, 2026 and April 30, 2027.  </p>
					<p>At the end of their residency, recipients are expected to write a short report of their work for publication on the Bruce Peel Special Collections website. They may be invited to give a public presentation about their work, either via our workshop series, an online lecture, or a blog post. It’s expected that the Fellowship be acknowledged in published works and presentations resulting from research conducted during the fellowship.</p>
					
				
				
				
				<h3>Award</h3>

				<p>The $2,000 CAD fellowship is awarded yearly to up to two recipients. Half of the award will be disbursed up front, and the other half upon completion of the final report. </p>
				
				<h3>Application  </h3>
				<p>Successful applications will demonstrate originality, feasibility, and how the research specifically utilizes the unique holdings at Bruce Peel Special Collections to contribute to local and global scholarly conversations.
				</p>
				<p>
				<a target="_blank" href="https://forms.gle/FvCMoJMz9XnTxZYs6"><strong><u>Application form</u></strong></a>. Applications are due Sunday, February 15, 2026. 
				</p>
				

				
				<h3>Adjudication</h3>
				<p>Fellowship applications are reviewed by a selection committee for originality and feasibility, with particular focus on how the research specifically utilizes the unique holdings at Bruce Peel Special Collections and contributes to the broader scholarly conversation.
				</p>
			

