			<p>
			The <strong>John Keenlyside Special Collections Research Fellowship</strong>
			 provides an opportunity for researchers to undertake research that requires substantial on-site use of material held in Bruce Peel Special Collections. The fellowship aims to promote innovative research and creative engagement with our collections. The $2,000 CAD award supports scholars who might otherwise be unable to travel to see the material in person. 
			</p>
			
			<p>
			In the development of their applications, we recommend that applicants familiarize themselves with the rare books and archival materials held in Bruce Peel Special Collections.  
			We recommend reviewing the <a href="https://bpsc.library.ualberta.ca/collections">Research Collections</a> and <a href="https://bpsc.library.ualberta.ca/exhibits">Exhibitions</a> webpages, 
			which provide descriptions of key holding areas. Use the <a href="https://search.library.ualberta.ca/discovery/search?vid=01UOA_INST:UOA&lang=en">Library catalogue</a> and Peel <a href="https://discoverarchives.library.ualberta.ca/bruce-peel-special-collections">finding aids</a> to search our collections.  
			</p>


				<h3>Eligibility</h3>

				<p>We invite all scholars, students, and community researchers living outside the greater Edmonton area to apply. We welcome applications from scholars using traditional archival and bibliographic methods, 
				as well as those pursuing creative, interdisciplinary, or non-traditional research approaches.</p>
				
